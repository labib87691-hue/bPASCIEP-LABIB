interface DemoSeedDefinition {
  academicYearId: string;
  examId: string;
  classCode: SupportedClassCode;
  rollNumber: string;
  studentId: string;
  studentCode?: string;
  studentNameEn: string;
  studentNameBn: string;
  section?: string;
  groupNameEn?: string;
  groupNameBn?: string;
  position?: number | null;
  workflowStatus: 'published' | 'draft' | 'approved';
  isPublished: boolean;
  publishedDateLabelBn?: string;
  publishedDateLabelEn?: string;
  marks: SubjectMarkInput[];
}

function buildDemoBundle(def: DemoSeedDefinition): ResultMarksheetBundle {
  const year = DEFAULT_ACADEMIC_YEARS.find((y) => y.id === def.academicYearId)!;
  const exam = DEFAULT_EXAMINATIONS.find((e) => e.id === def.examId)!;
  const cls = SUPPORTED_RESULT_CLASSES.find((c) => c.classCode === def.classCode)!;
  const ruleId =
    exam.gradingRuleOverrides?.[def.classCode] || cls.defaultGradingRuleId;
  const rule = DEFAULT_GRADING_RULES.find((r) => r.id === ruleId)!;

  const summary = calculateInstitutionalResult(def.marks, rule);
  const resultId = buildResultDocId(
    def.academicYearId,
    def.examId,
    def.classCode,
    def.rollNumber
  );

  const resultRecord: StudentResultRecord = {
    id: resultId,
    academicYearId: def.academicYearId,
    academicYearLabelBn: year.labelBn,
    academicYearLabelEn: year.labelEn,
    examId: def.examId,
    examNameBn: exam.nameBn,
    examNameEn: exam.nameEn,
    classCode: def.classCode,
    classNameBn: cls.nameBn,
    classNameEn: cls.nameEn,
    rollNumber: def.rollNumber,
    studentId: def.studentId,
    studentCode: def.studentCode,
    studentNameEn: def.studentNameEn,
    studentNameBn: def.studentNameBn,
    section: def.section,
    groupNameEn: def.groupNameEn,
    groupNameBn: def.groupNameBn,
    gradingRuleId: rule.id,
    totalFullMarks: summary.totalFullMarks,
    obtainedTotalMarks: summary.obtainedTotalMarks,
    percentage: summary.percentage,
    gpa: summary.gpa,
    gpaWithoutOptional: summary.gpaWithoutOptional,
    calculateGpa: rule.calculateGpa,
    calculatePercentage: rule.calculatePercentage,
    maxGpa: rule.maxGpa,
    letterGrade: summary.letterGrade,
    finalStatus: summary.finalStatus,
    compulsorySubjectCount: summary.compulsorySubjectCount,
    failedCompulsoryCount: summary.failedCompulsoryCount,
    position: exam.showPosition ? def.position ?? null : null,
    showPosition: exam.showPosition && def.position != null,
    workflowStatus: def.workflowStatus,
    isPublished: def.isPublished,
    publishedDateLabelBn: def.publishedDateLabelBn,
    publishedDateLabelEn: def.publishedDateLabelEn,
    isDemoRecord: true,
  };

  const subjectRecords: ResultSubjectMarkRecord[] = summary.subjects.map((s) => ({
    id: buildResultSubjectDocId(resultId, s.subjectCode),
    resultId,
    academicYearId: def.academicYearId,
    examId: def.examId,
    classCode: def.classCode,
    rollNumber: def.rollNumber,
    subjectId: s.subjectId,
    subjectCode: s.subjectCode,
    subjectNameBn: s.subjectNameBn,
    subjectNameEn: s.subjectNameEn,
    fullMarks: s.fullMarks,
    passMarks: s.passMarks,
    isOptional: s.isOptional,
    hasComponents: s.hasComponents,
    hasPractical: s.hasPractical,
    writtenFullMarks: s.writtenFullMarks,
    mcqFullMarks: s.mcqFullMarks,
    practicalFullMarks: s.practicalFullMarks,
    writtenMarks: s.writtenMarks ?? null,
    mcqMarks: s.mcqMarks ?? null,
    practicalMarks: s.practicalMarks ?? null,
    obtainedMarks: s.obtainedMarks,
    isAbsent: Boolean(s.isAbsent),
    letterGrade: s.letterGrade,
    gradePoint: s.gradePoint,
    isPassed: s.isPassed,
    displayOrder: s.displayOrder,
    isPublished: def.isPublished,
  }));

  return {
    result: resultRecord,
    subjects: subjectRecords,
    gradingRule: rule,
  };
}

